    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        // TODO add your handling code here:
        JTextField username = new JTextField();
        JPasswordField password = new JPasswordField();
        String pass, user;
 
        Object[] comp = {
            "Username:", username,
            "Password:", password
        };
 
        if (evt.getSource() == loginBtn) {
            System.out.println("[Notice]: Attempting to login to an account.");
            int option = JOptionPane.showConfirmDialog(null, comp, "Login", JOptionPane.OK_CANCEL_OPTION);
            if (option == JOptionPane.OK_OPTION) {
                user = username.getText();
                pass = new String(password.getPassword());
 
                if (database.validateLogin(user, pass)) {
                    System.out.println("[Success]: Logged in as: " + user);
                    userText.setText("Logged in as: "+ user);
                    if (options != null) {
                        options.setCurrentUser(database.getUserId(user)); // Settings now save for this user
                    }
                    // TODO: once a "currently logged in as" label exists on this
                    // panel, set its text here (e.g. currentUserText.setText("Logged in as: " + user);)
                    this.swapCard(bottomPanel, "loggedIn");
                } else {
                    System.out.println("[Error]: Could not successfully login.");
                    JOptionPane.showMessageDialog(null, "Invalid username or password", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            }
        } else if (evt.getSource() == signUpBtn) {
            System.out.println("[Notice]: Creating a new account.");
            int option = JOptionPane.showConfirmDialog(null, comp, "Sign Up", JOptionPane.OK_CANCEL_OPTION);
 
            if (option == JOptionPane.OK_OPTION) {
                user = username.getText();
                pass = new String(password.getPassword());
 
                if (database.registerUser(user, pass)) {
                    System.out.println("[Success]: Account created for: " + user);
                    // TODO: auto-login or prompt the user to log in now that the account exists
                } else {
                    System.out.println("[Error]: Failed to create account.");
                    JOptionPane.showMessageDialog(null, "User already taken or invalid input.", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_loginActionPerformed

    private void signoutPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signoutPerformed
        int option = JOptionPane.showConfirmDialog(null, "Are you sure you want to log out?", "Log out", JOptionPane.OK_CANCEL_OPTION);
        if (option == JOptionPane.OK_OPTION) {
            System.out.println("[Notice]: Signed out.");
            userText.setText("");
            if (options != null) {
                options.setCurrentUser(Options.GUEST); // Stop saving settings for the old user
            }
            // TODO: clear the "currently logged in as" label here too, once it exists
            this.swapCard(bottomPanel, "loggedOut");
        }
    }//GEN-LAST:event_signoutPerformed

